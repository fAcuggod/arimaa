def tablero_bien_formado(t : Tablero) -> bool:
    if (len(t) == ALTO):
        for fila in t:
            if (len(fila) != ANCHO):
                return False
        return True
    else: 
        return False

def juego_bien_formado(j : Juego) -> bool:
    return (tablero_bien_formado(j.tablero) & (0 <= j.pasos_consumidos) & (j.pasos_consumidos < MAX_PASOS))

